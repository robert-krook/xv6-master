void 
vga_draw_rect_border (int color, int x, int y, int width, int height)
{
    if (x >= SCREEN_WIDTH || x + width < 0 || y >= SCREEN_HEIGHT || y + height < 0 || width < 0 || height < 0)
    {
        return;
    }

    int i;

    //int max_line = (SCREEN_WIDTH - x) < width ? (SCREEN_WIDTH - x) : width;
    //RGB *t = buf + y * SCREEN_WIDTH + x;

    if (y > 0)
    {
        for (i = 0; i < width; i++)
        {
            if (x + i > 0 && x + i < SCREEN_WIDTH)
            {
                vga_draw_pixel(x + i, y, color);
                //*(t + i) = color;
            }
        }
    }

    if (y + height < SCREEN_HEIGHT)
    {
        //RGB *o = t + height * SCREEN_WIDTH;
        for (i = 0; i < width; i++)
        {
            if (y > 0 && x + i > 0 && x + i < SCREEN_WIDTH)
            {
                vga_draw_pixel(x + i, y + height, color);
                //*(o + i) = color;
            }
        }
    }

    if (x > 0)
    {
        for (i = 0; i < height; i++)
        {
            if (y + i > 0 && y + i < SCREEN_HEIGHT)
            {
                //*(t + i * SCREEN_WIDTH) = color;
                vga_draw_pixel(x, y + i, color);
            }
        }
    }

    if (x + width < SCREEN_WIDTH)
    {
        //RGB *o = t + width;
        for (i = 0; i < height; i++)
        {
            if (y + i > 0 && y + i < SCREEN_HEIGHT)
            {
                vga_draw_pixel(x + width, y + i, color);
                //*(o + i * SCREEN_WIDTH) = color;
            }
        }
    }
}
