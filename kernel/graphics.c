int 
vga_draw_pixel (int x, int y, int color) 
{
    // 1. Calculate offset and bit mask
    unsigned int base = (y * 640) + x;
    unsigned int offset = base >> 3;       // divide by 8 for byte offset
    unsigned char bitmask = 0x80 >> (x & 0x7); // 1 shifted by remainder
    
    // 2. Plot color plane by plane
    for (int plane = 0; plane < 4; plane++) 
    {
        // Write the bit to video memory (using dummy read-before-write or direct map)
       if ((color >> plane) & 0x01) {
            offscreen_buffer [plane][offset] |= bitmask; //(offscreen_buffer[plane][index] | mask);
        } else {
            offscreen_buffer [plane][offset] &= ~bitmask; 
        }
    }
    return 0;
}

int 
vga_blit (void) 
{
	unsigned char * fb = (unsigned char *) P2V(0xa0000);
	int p;
	for(p = 0; p < 4; p++){
		set_plane(p);
		memmove(fb, offscreen_buffer[p], 640*480/8); 
	}
	return 0;
}

int 
vga_clear_screen (void) 
{
	//call draw pixel on offscreen_buffer
 	int x;
	int y;
	for(x = 0; x < 640; x++) 
	{	
		for( y = 0; y < 480; y++) 
		{
			vga_draw_pixel(x, y, 0);
		}
	}

	//Call blit to copy over buffer
	vga_blit();
	return 0;
}

//Bresenham's algorithm Taken and adjusted from http://rosettacode.org/wiki/Bitmap/Bresenham's_line_algorithm#C
int 
vga_draw_line (int x1, int y1, int x2, int y2, int color) 
{
	int xdiff = x2 - x1;
	int ydiff = y2 - y1;
	
	int dx = xdiff * ( (xdiff < 0) * (-1) + (xdiff > 0)), sx = x1 < x2 ? 1 : -1;
	int dy = ydiff * ( (ydiff < 0) * (-1) + (ydiff > 0)), sy = y1 < y2 ? 1 : -1;
	int err = (dx > dy ? dx : -dy)/2, e2;

	for(;;)
    {
		vga_draw_pixel(x1, y1, color);
		if(x1 == x2 && y1 == y2) break;
		e2 = err;
		if(e2 > -dx) { err -= dy; x1 += sx; }
		if(e2 < dy) { err += dx; y1 += sy; }
	}

	return 0;
}

